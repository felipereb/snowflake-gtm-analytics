-- Account setup: cost guardrails, warehouses, database, roles.
-- Run once in a Snowsight worksheet. Safe to rerun.
-- Replace <your_user_name> with the exact `name` from SHOW USERS.
-- If that name was created in lowercase, keep the double quotes (Snowflake uppercases unquoted names).

-- ============ 1. COST GUARDRAILS ============
USE ROLE ACCOUNTADMIN;

CREATE OR REPLACE RESOURCE MONITOR rm_trial_cap
  WITH CREDIT_QUOTA = 50
  FREQUENCY = MONTHLY
  START_TIMESTAMP = IMMEDIATELY
  TRIGGERS
    ON 50 PERCENT DO NOTIFY
    ON 80 PERCENT DO NOTIFY
    ON 100 PERCENT DO SUSPEND_IMMEDIATE;

ALTER ACCOUNT SET RESOURCE_MONITOR = rm_trial_cap;
ALTER WAREHOUSE IF EXISTS COMPUTE_WH SET AUTO_SUSPEND = 60;

-- ============ 2. WAREHOUSES ============
USE ROLE SYSADMIN;

CREATE WAREHOUSE IF NOT EXISTS LOAD_WH
  WAREHOUSE_SIZE = XSMALL AUTO_SUSPEND = 60 AUTO_RESUME = TRUE INITIALLY_SUSPENDED = TRUE;

CREATE WAREHOUSE IF NOT EXISTS TRANSFORM_WH
  WAREHOUSE_SIZE = XSMALL AUTO_SUSPEND = 60 AUTO_RESUME = TRUE INITIALLY_SUSPENDED = TRUE;

-- ============ 3. DATABASE ============
CREATE DATABASE IF NOT EXISTS GTM;
CREATE SCHEMA IF NOT EXISTS GTM.RAW;

-- ============ 4. ROLES AND GRANTS ============
USE ROLE SECURITYADMIN;

CREATE ROLE IF NOT EXISTS LOADER;
CREATE ROLE IF NOT EXISTS TRANSFORMER;
CREATE ROLE IF NOT EXISTS REPORTER;
CREATE ROLE IF NOT EXISTS MCP_READONLY;

GRANT ROLE LOADER, TRANSFORMER, REPORTER, MCP_READONLY TO ROLE SYSADMIN;

GRANT USAGE ON WAREHOUSE LOAD_WH TO ROLE LOADER;
GRANT USAGE ON DATABASE GTM TO ROLE LOADER;
GRANT ALL ON SCHEMA GTM.RAW TO ROLE LOADER;

GRANT USAGE ON WAREHOUSE TRANSFORM_WH TO ROLE TRANSFORMER;
GRANT USAGE, CREATE SCHEMA ON DATABASE GTM TO ROLE TRANSFORMER;
GRANT USAGE ON SCHEMA GTM.RAW TO ROLE TRANSFORMER;
GRANT SELECT ON FUTURE TABLES IN SCHEMA GTM.RAW TO ROLE TRANSFORMER;

-- REPORTER and MCP_READONLY get read access to marts once dbt creates them (weeks 2 and 3).

-- ============ 5. GIVE THE ROLES TO YOUR USER ============
-- The trial user is owned by ACCOUNTADMIN.
USE ROLE ACCOUNTADMIN;
GRANT ROLE LOADER      TO USER "<your_user_name>";
GRANT ROLE TRANSFORMER TO USER "<your_user_name>";
GRANT ROLE REPORTER    TO USER "<your_user_name>";

-- ============ 6. CHECKS ============
SHOW GRANTS TO USER "<your_user_name>";
SHOW WAREHOUSES;
SHOW RESOURCE MONITORS;
SHOW PARAMETERS LIKE 'CORTEX_ENABLED_CROSS_REGION' IN ACCOUNT;
